"""Writes docs/RESULTS.md, a Markdown summary of the main results, from results/tables/*.csv (so it never goes out of date)."""
import ast, json, os
import pandas as pd

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
T = os.path.join(ROOT, "results", "tables")
rd = lambda f: pd.read_csv(os.path.join(T, f + ".csv"))
S = rd("summary_all_configs").set_index("config"); CAL = rd("calibration_single_vs_ensemble").set_index("config"); CMP = rd("config_comparisons")
CI = lambda s: ast.literal_eval(s)
f4 = lambda x: f"{x:.4f}"; f3 = lambda x: f"{x:.3f}"
NICE = {"date_full": "BERTweet-base (DATE)", "bertweet_large": "BERTweet-large", "roberta_base": "RoBERTa-base", "bert_base": "BERT-base", "distilbert": "DistilBERT-base", "xlm_roberta": "XLM-RoBERTa-base",
        "twitter_roberta": "Twitter-RoBERTa-base", "twitter_roberta_hate": "Twitter-RoBERTa-hate", "twhin_bert": "TwHIN-BERT-base", "toxic_bert": "Toxic-BERT"}

def md(headers, rows):
    out = ["| " + " | ".join(headers) + " |", "|" + "|".join("---" for _ in headers) + "|"]
    return "\n".join(out + ["| " + " | ".join(str(c) for c in r) + " |" for r in rows])

st = json.load(open(os.path.join(T, "dataset_stats.json")))
d = S.loc["date_full"]; c = CAL.loc["date_full"]; a = CI(d.test_ens_acc_ci); e = CI(d.test_ens_ece_ci); de = CI(c.delta_ece_ci)
parts = ["# Results summary\n\n*Generated by `analysis/make_results_summary.py` from `results/tables/`; do not edit by hand. Single seed (42) unless a multi-seed table is present.*\n",
         f"## Data\nTrain part: {st['train_n']:,} posts ({st['train_ext_pct']:.1f}% extremist). Test part: {st['test_n']:,} labelled posts ({st['test_ext_pct']:.1f}% extremist). SHA-256 of the data file: `{st['sha256']}`.\n",
         "## Main result: DATE on the held-out test posts\n" + md(["Metric", "Single fold models (mean +- sd)", "10-model ensemble"], [
             ["Accuracy", f"{d.test_single_acc_mean:.4f} +- {d.test_single_acc_std:.4f}", f"{d.test_ens_acc:.4f} (95% CI {a[0]:.4f}-{a[1]:.4f})"], ["Macro-F1", "-", f4(d.test_ens_f1_macro)], ["ROC-AUC", "-", f4(d.test_ens_auc)],
             ["PR-AUC (extremist)", "-", f4(d.test_ens_pr_auc)], ["Balanced accuracy", "-", f4(d.test_ens_bal_acc)], ["ECE (15 bins)", f4(d.test_single_ece_mean), f"{d.test_ens_ece15:.4f} (95% CI {e[0]:.4f}-{e[1]:.4f})"],
             ["Brier score", f4(d.test_single_brier_mean), f4(d.test_ens_brier_sum)], ["NLL", f4(d.test_single_nll_mean), f4(d.test_ens_nll)]]) +
         f"\n\nEnsemble minus mean single-model ECE: {c.delta_ece:+.4f} (95% CI {de[0]:+.4f} to {de[1]:+.4f}). 10-fold cross-validation (single models): accuracy {d.cv_acc_mean:.4f} +- {d.cv_acc_std:.4f}.\n"]

order = [k for k in ["distilbert", "bert_base", "toxic_bert", "xlm_roberta", "twhin_bert", "roberta_base", "twitter_roberta", "twitter_roberta_hate", "date_full", "bertweet_large"] if k in S.index]
parts.append("## Encoders under one protocol\n" + md(["Encoder", "Params (M)", "CV acc.", "Test acc. (ens.)", "Test macro-F1", "Test AUC", "Test ECE"],
             [[NICE[k], f"{S.loc[k].params_millions_single:.0f}", f"{S.loc[k].cv_acc_mean:.4f} +- {S.loc[k].cv_acc_std:.4f}", f4(S.loc[k].test_ens_acc), f4(S.loc[k].test_ens_f1_macro), f4(S.loc[k].test_ens_auc), f4(S.loc[k].test_ens_ece15)] for k in order]) + "\n")

ab = [("date_full", "Full DATE"), ("no_aug", "without augmentation"), ("no_cw", "without class weights"), ("no_cosine", "without cosine schedule"), ("aug_ctx_only", "contextual substitution only"), ("aug_eda_only", "random edits only"), ("date_grouped", "duplicate-grouped folds")]
rows = []
for k, nm in ab:
    if k not in S.index: continue
    r = S.loc[k]; ct = CMP[(CMP.vs == k) & (CMP.on == "test_ensemble")]; co = CMP[(CMP.vs == k) & (CMP.on == "oof_pooled")]
    rows.append([nm, f4(r.oof_pooled_acc), f4(r.test_ens_acc), f4(r.test_ens_ece15), "-" if co.empty else f3(co.mcnemar_p.iloc[0]), "-" if ct.empty else f3(ct.mcnemar_p.iloc[0])])
parts.append("## Ablation (McNemar p-values against the full configuration)\n" + md(["Configuration", "OOF acc.", "Test acc.", "Test ECE", "p (OOF)", "p (test)"], rows) + "\n")

parts.append("## Calibration: single models versus ensemble (test ECE)\n" + md(["Configuration", "Single", "Single + temperature scaling", "Ensemble", "Delta ECE [95% CI]"],
             [[k, f4(CAL.loc[k].ece_single_mean), f4(CAL.loc[k].ece_single_tempscaled), f4(CAL.loc[k].ece_ensemble), f"{CAL.loc[k].delta_ece:+.4f} [{CI(CAL.loc[k].delta_ece_ci)[0]:+.4f}, {CI(CAL.loc[k].delta_ece_ci)[1]:+.4f}]"]
              for k in ["date_full", "no_aug", "no_cw", "no_cosine", "roberta_base", "twitter_roberta", "twhin_bert", "bertweet_large"] if k in CAL.index]) + "\n")

lc = rd("augmentation_studies"); lcr = []
for fr in (0.25, 0.5, 1.0):
    row = [f"{int(fr*100)}%"]
    for b in ("date_full", "no_aug"):
        x = lc[(lc.study == "learning_curve") & (lc.frac == fr) & (lc.config.str.startswith(b))]
        row += ["-", "-"] if x.empty else [f4(x.oof_acc.iloc[0]), f4(x.test_ens_acc.iloc[0])]
    lcr.append(row)
parts.append("## Learning curve (with and without augmentation)\n" + md(["Training data", "OOF acc. (aug.)", "Test acc. (aug.)", "OOF acc. (no aug.)", "Test acc. (no aug.)"], lcr) + "\n")

rb = rd("robustness_and_fairness_probes"); rb = rb[rb.config == "date_full"]
parts.append("## Robustness and identity-term probes (DATE ensemble)\n" + md(["Perturbation", "n", "Accuracy (clean)", "Prediction flips"], [[r.perturbation, int(r.n), f"{r.ens_acc:.3f} ({r.ens_acc_clean:.3f})", f"{r.ens_flip_rate*100:.1f}%"] for r in rb.itertuples()]) + "\n")

ex = rd("external_transfer"); ex = ex[ex.config == "date_full"]
parts.append("## External transfer (zero-shot, DATE ensemble)\n" + md(["Dataset", "n", "% positive", "ROC-AUC", "PR-AUC"], [[r.external, int(r.n), f"{r.pos_pct:.0f}", f3(r.ens_auc), f3(r.ens_pr_auc)] for r in ex.itertuples()]) + "\n")

bl = rd("classical_baselines")
parts.append("## Classical baselines\n" + md(["Model", "CV acc.", "Test acc.", "Test macro-F1"], [[r.model, f"{r.cv_acc_mean:.4f} +- {r.cv_acc_std:.4f}", f4(r.test_acc), f4(r.test_f1_macro)] for r in bl.itertuples()]) + "\n")

ms = os.path.join(T, "multiseed_summary.csv")
if os.path.exists(ms) and os.path.getsize(ms) > 5:
    m = pd.read_csv(ms)
    if len(m): parts.append("## Multi-seed results\n" + md(["Configuration", "Seeds", "Test acc. (mean +- sd)", "OOF acc. (mean +- sd)", "Test ECE (mean)"], [[r.config, int(r.n_seeds), f"{r.test_ens_acc_mean:.4f} +- {r.test_ens_acc_std:.4f}", f"{r.oof_acc_mean:.4f} +- {r.oof_acc_std:.4f}", f4(r.test_ens_ece_mean)] for r in m.itertuples()]) + "\n")

out = os.path.join(ROOT, "docs", "RESULTS.md"); os.makedirs(os.path.dirname(out), exist_ok=True)
open(out, "w", encoding="utf8", newline="\n").write("\n".join(parts))
print("wrote docs/RESULTS.md")
